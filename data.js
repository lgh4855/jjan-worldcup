 const E=x=>String(x??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
 const catOf=g=>CATS.some(c=>c.id===g.c)?g.c:'etc';
 let cur='all';try{cur=localStorage.getItem('jj-cat')||'all'}catch{}
 if(cur!=='all'&&!GENRES.some(g=>catOf(g)===cur))cur='all';
